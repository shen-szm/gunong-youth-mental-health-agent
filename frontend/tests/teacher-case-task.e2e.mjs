test('PC intent clarification preserves constraints and cannot silently resume', { skip: !run, timeout: 60000 }, async () => {
  const browser = await chromium.launch({ executablePath: process.env.EDGE_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } })
    const login = await context.request.post(`${base}/api/user/login`, { data: { username: 'admin_a', password: 'AdminTeacherPassword12' } })
    assert.equal(login.status(), 200)
    const user = await login.json()
    await context.addInitScript(user => {
      localStorage.setItem('shengyu_user_id', String(user.user_id))
      localStorage.setItem('shengyu_is_admin', '1')
      localStorage.setItem('shengyu_is_super_admin', '1')
      localStorage.setItem('shengyu_role', 'admin_teacher')
    }, user)
    const page = await context.newPage()
    const errors = [], mutations = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.method() === 'POST' && /\/tasks\/(case-plans|durable-plans)/.test(request.url())) mutations.push(request.url()) })
    await page.goto(`${base}/admin`)
    await page.locator('[data-nav-id="cases"]').click()
    await page.locator('.case-student').filter({ hasText: '合成学生A' }).click()
    const intent = page.getByRole('region', { name: '自然语言需求预览', exact: true })
    const goal = intent.getByRole('textbox', { name: '任务需求', exact: true })
    const original = '使用授权内30天记录准备沟通报告和清单，不检索。不要发送消息。'
    await goal.fill(original)
    await intent.locator('.intent-consent input').first().check()
    await intent.getByRole('button', { name: '解析需求，不执行', exact: true }).click()
    const review = intent.getByRole('region', { name: '需要人工澄清' })
    await review.waitFor()
    assert.equal(await review.locator('blockquote').innerText(), original)
    assert.ok((await review.innerText()).includes('对外发送或公开'))
    assert.equal(await goal.inputValue(), original)
    // A later model response must not erase the unresolved local review.
    await page.route('**/api/teacher/tasks/intent-preview', route => route.fulfill({ json: { status: 'ready_for_review', source: 'model_extracted', can_prepare: true, contract: { objective: 'conversation_preparation', period_days: 30, output_format: 'checklist', resource_policy: 'not_needed' } } }))
    await goal.fill('使用授权内30天记录准备沟通报告和清单，不检索。')
    await intent.locator('.intent-consent input').first().check()
    await intent.getByRole('button', { name: '解析需求，不执行', exact: true }).click()
    await intent.getByText('再次解析已返回，但原始要求仍待澄清；本轮不采用候选合同。', { exact: true }).waitFor()
    assert.equal(await intent.locator('dl').count(), 0)
    assert.equal(await review.locator('blockquote').innerText(), original)
    assert.equal(await intent.locator('fieldset').count(), 0)
    for (const width of [1280, 1440, 1920]) {
      await page.setViewportSize({ width, height: 1080 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
    }
    if (process.env.TEACHER_TASK_SCREENSHOTS === '1') await intent.screenshot({ path: '../.codex-intent-clarification-pc.png' })
    assert.equal(await page.evaluate(text => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }).includes(text), original), false)
    assert.deepEqual(mutations, [])
    assert.deepEqual(errors, [])
  } finally { await browser.close() }
})

