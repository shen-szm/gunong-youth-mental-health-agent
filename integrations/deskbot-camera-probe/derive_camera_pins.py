"""Trace the original EasyEDA PCB nets to U4 symbol pins, without reading firmware.

Usage: python derive_camera_pins.py PATH_TO_NATIVE_DOCS_JSON
The module-to-connector contact relation remains a physical assumption.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

PCB_UUID = "6d346aee3d67e255"
SYMBOL_UUID = "375300749f2d286f"
# Transcribed from the user's OV2640 module drawing, not a GPIO configuration.
MODULE = ["NC", "AGND", "SDA", "AVDD", "SCL", "RESET", "VSYNC", "PWDN",
          "HREF", "DVDD", "DOVDD", "Y9", "MCLK", "Y8", "DGND", "Y7",
          "PCLK", "Y6", "Y2", "Y5", "Y3", "Y4", "Y1", "Y0"]
NETS = {"SDA": "CAM_SDA", "SCL": "CAM_SCL", "MCLK": "XMCLK",
        **{s: "DVP_" + s for s in ["VSYNC", "HREF", "PCLK"] +
           [f"Y{i}" for i in range(2, 10)]}}


def derive(source):
    raw = source.read_bytes()
    docs = {d["data"]["uuid"]: d for d in json.loads(raw.decode("utf-8-sig"))}
    pcb = docs[PCB_UUID]
    refs = {v["value"]: v["parentId"] for h, v in pcb["records"]
            if h["type"] == "ATTR" and v.get("key") == "Designator"}
    pads = {}
    for ref in ["FPC1", "U4"]:
        pads[ref] = {}
        for h, v in pcb["records"]:
            if h["type"] == "PAD_NET":
                _, component, num, _ = json.loads(h["id"])
                if component == refs[ref]:
                    pads[ref][int(num)] = v["padNet"]
    attrs = {}
    for h, v in docs[SYMBOL_UUID]["records"]:
        if h["type"] == "ATTR" and v.get("key") in ["Pin Number", "Pin Name"]:
            attrs.setdefault(v["parentId"], {})[v["key"]] = str(v["value"])
    names = {int(a["Pin Number"]): a["Pin Name"] for a in attrs.values()
             if "Pin Number" in a and "Pin Name" in a}

    def trace(reverse):
        rows = []
        for num, signal in enumerate(MODULE, 1):
            pad = 25 - num if reverse else num
            net = pads["FPC1"][pad]
            gpio_pins = [(p, int(names[p][2:])) for p, n in pads["U4"].items()
                         if net and net == n and re.fullmatch(r"IO\d+", names.get(p, ""))]
            if len(gpio_pins) > 1:
                raise ValueError(f"Ambiguous MCU connection: {net}")
            terminal, gpio = gpio_pins[0] if gpio_pins else (None, None)
            rows.append(dict(module_pin=num, signal=signal, fpc_pad=pad,
                             net=net or "NC", u4_terminal=terminal, gpio=gpio))
        return rows

    intended, same_number = trace(True), trace(False)
    by_signal = {r["signal"]: r for r in intended}
    for signal, expected_net in NETS.items():
        row = by_signal[signal]
        if row["net"] != expected_net or row["gpio"] is None:
            raise ValueError(f"Incomplete or inconsistent route: {row}")
    if len({by_signal[s]["gpio"] for s in NETS}) != len(NETS):
        raise ValueError("Duplicate camera GPIO")
    for signal, expected_net in {"AGND": "GND", "DGND": "GND", "AVDD": "VCC_2V8",
                                 "DVDD": "VCC_1V2", "DOVDD": "VCC_2V8"}.items():
        if by_signal[signal]["net"] != expected_net:
            raise ValueError(f"Unexpected supply connection: {signal}")
    for signal in ["RESET", "PWDN"]:
        if by_signal[signal]["gpio"] is not None:
            raise ValueError(f"Re-evaluate control circuit: {signal}")

    out = Path(__file__).resolve().parent
    evidence = dict(source=str(source.resolve()), sha256=hashlib.sha256(raw).hexdigest(),
                    pcb_uuid=PCB_UUID, mcu_symbol_uuid=SYMBOL_UUID,
                    components={r: refs[r] for r in pads},
                    module_source="User supplied OV2640-200mm-160 drawing",
                    limitation="FPC pad = 25 - module pin is the intended contact relation; physical insertion is unverified. This does not establish sensor supply compatibility.",
                    intended_contact_mapping=intended, same_number_hypothesis=same_number)
    (out / "pin_trace.json").write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["#pragma once", "", "// Generated by derive_camera_pins.py from native PCB PAD_NET and U4 symbol records.",
             f"// PCB {PCB_UUID}; source SHA256 {evidence['sha256']}",
             "// Assumes module contact n reaches FPC1 pad 25-n. Verify physical insertion separately.",
             "namespace camera_pins {", "constexpr int kPwdn = -1;  // FPC1.17: external pulldown, no U4 GPIO",
             "constexpr int kReset = -1; // FPC1.19: external pullup, no U4 GPIO"]
    for signal, name in [("MCLK", "Xclk"), ("SDA", "Sda"), ("SCL", "Scl"),
                         ("PCLK", "Pclk"), ("VSYNC", "Vsync"), ("HREF", "Href")] + [(f"Y{i}", f"Y{i}") for i in range(2, 10)]:
        r = by_signal[signal]
        lines.append(f"constexpr int k{name} = {r['gpio']}; // module {r['module_pin']} {signal} -> FPC1.{r['fpc_pad']} -> {r['net']} -> U4.{r['u4_terminal']} IO{r['gpio']}")
    lines += ["constexpr int kData[8] = {kY2, kY3, kY4, kY5, kY6, kY7, kY8, kY9};",
              "} // namespace camera_pins", ""]
    (out / "src" / "camera_pins_from_schematic.h").write_text("\n".join(lines), encoding="utf-8")
    print("Derived 14 distinct camera GPIOs from PCB and U4 symbol; header and pin_trace.json written.")


if __name__ == "__main__":
    derive(Path(sys.argv[1]))
